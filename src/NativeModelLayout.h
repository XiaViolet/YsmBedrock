inline constexpr std::uintptr_t modelVtable = 0xf268ae0;

// The launchers append different loader sections after the original game.
// Pin the sections containing the called functions and their type information.
inline bool supportedSections(IMAGE_NT_HEADERS64 const& nt) {
    if (nt.Signature != IMAGE_NT_SIGNATURE || nt.FileHeader.Machine != IMAGE_FILE_MACHINE_AMD64
        || nt.FileHeader.TimeDateStamp != 0x6ad79ee4 || nt.OptionalHeader.Magic != IMAGE_NT_OPTIONAL_HDR64_MAGIC
        || nt.FileHeader.SizeOfOptionalHeader != sizeof(IMAGE_OPTIONAL_HEADER64) || nt.FileHeader.NumberOfSections < 2
        || nt.OptionalHeader.SizeOfImage < 0x12308000) return false;
    auto sections = IMAGE_FIRST_SECTION(&nt);
    auto const& code = sections[0];
    auto const& data = sections[1];
    return std::memcmp(code.Name, ".text\0\0", IMAGE_SIZEOF_SHORT_NAME) == 0
        && code.VirtualAddress == 0x1000 && code.Misc.VirtualSize == 0xeec59d6
        && code.Characteristics == (IMAGE_SCN_CNT_CODE | IMAGE_SCN_MEM_EXECUTE | IMAGE_SCN_MEM_READ)
        && std::memcmp(data.Name, ".rdata\0", IMAGE_SIZEOF_SHORT_NAME) == 0
        && data.VirtualAddress == 0xeec7000 && data.Misc.VirtualSize == 0x3440ea4
        && data.Characteristics == (IMAGE_SCN_CNT_INITIALIZED_DATA | IMAGE_SCN_MEM_READ);
}
template<std::size_t N> inline bool matches(std::uintptr_t base, std::uintptr_t offset, unsigned char const (&bytes)[N]) {
    return std::memcmp(reinterpret_cast<void const*>(base + offset), bytes, N) == 0;
}
inline bool supports(std::uintptr_t base, std::uintptr_t vtable) {
    if (!base || vtable != base + modelVtable) return false;
    auto const* dos = reinterpret_cast<IMAGE_DOS_HEADER const*>(base);
    if (dos->e_magic != IMAGE_DOS_SIGNATURE) return false;
    auto const* nt = reinterpret_cast<IMAGE_NT_HEADERS64 const*>(base + dos->e_lfanew);
    return supportedSections(*nt) && matches(base, modelConstructor, modelSignature)
        && matches(base, definitionCopy, copySignature) && matches(base, definitionDestroy, destroySignature);
}
