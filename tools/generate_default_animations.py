"""Embed the CC0 default animations from the official Java YSM release."""
import argparse
import hashlib
import io
import json
import pathlib
import zipfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
RELEASE = "2.6.5-neoforge+mc26.1-hotfix"
RELEASE_ID = "1rPJlKDJ"
JAR_SHA512 = ("b5e2445022e6c071b49c7eb312bc2e1628980a615506414a6ced06950999b8f"
              "627829cebe848bd8a2dc025c121abfb4286221bb641ad7648b13446e78dc07df3")
PREFIX = "assets/yes_steve_model/builtin/default/"


def read_animations(archive):
    sources = {}

    def read(relative):
        raw = archive.read(PREFIX + relative)
        sources[relative] = hashlib.sha256(raw).hexdigest()
        return json.loads(raw.decode("utf-8-sig"))

    descriptor = read("ysm.json")
    if descriptor["metadata"]["license"]["type"] != "CC 0":
        raise RuntimeError("Default animation asset license changed")
    body, arm = {}, {}
    for group, relative in descriptor["files"]["player"]["animation"].items():
        clips = read(relative)["animations"]
        target = arm if group == "fp_arm" else body
        for name, clip in clips.items():
            if name in target:
                raise RuntimeError("Duplicate default animation: " + name)
            target[name] = clip
    replaced = {}
    for kind, group in [('projectile', 'projectiles'), ('vehicle', 'vehicles')]:
        for target in descriptor['files'].get(group, []):
            canonical = '\0'.join(sorted(target['match'])).encode('utf-8')
            domain = kind + '/' + hashlib.sha256(canonical).hexdigest()[:16] + '/main'
            relative = target.get('animation')
            clips = read(relative)['animations'] if relative else {}
            if domain in replaced:
                raise RuntimeError('Duplicate default target domain: ' + domain)
            replaced[domain] = clips
    return body, arm, replaced, sources


def generate(jar, output):
    data = jar.read_bytes()
    if hashlib.sha512(data).hexdigest() != JAR_SHA512:
        raise RuntimeError("Expected the pinned official YSM release JAR")
    with zipfile.ZipFile(io.BytesIO(data)) as archive:
        body, arm, replaced, sources = read_animations(archive)
    lines = ["// Generated by tools/generate_default_animations.py; CC0 default model assets.",
             f"// Official Java YSM release: {RELEASE} ({RELEASE_ID}), SHA-512 {JAR_SHA512}"]
    lines.extend("// " + path + " sha256=" + digest for path, digest in sources.items())
    for symbol, clips in [("DefaultBodyAnimations", body), ("DefaultFirstPersonAnimations", arm),
                          ("DefaultTargetAnimationSets", replaced)]:
        payload = json.dumps(clips, ensure_ascii=True, separators=(",", ":"))
        if ')ysmdef"' in payload:
            raise RuntimeError("Raw string delimiter collision")
        lines.append('constexpr char ' + symbol + '[] = R"ysmdef(' + payload + ')ysmdef";')
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(json.dumps({"body": len(body), "first_person": len(arm),
                      "replaced_clips": sum(map(len, replaced.values())), "replaced_targets": len(replaced),
                      "release": RELEASE, "source_files": len(sources)}))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("jar", type=pathlib.Path)
    parser.add_argument("--output", type=pathlib.Path, default=ROOT / "src/DefaultAnimations.inc")
    args = parser.parse_args()
    generate(args.jar, args.output)
