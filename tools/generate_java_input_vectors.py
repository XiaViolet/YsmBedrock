"""Run the unmodified official 1.20.1 ElytraModel against minimal state carriers."""
import hashlib
import json
import pathlib
import subprocess
import zipfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
WORK = ROOT / 'build/verification/java-input-oracle-0.20'
WORK.mkdir(exist_ok=True)
toolchain = json.loads((ROOT / 'build/verification/java-reference-toolchain.json').read_text(encoding='utf-8-sig'))
sources = {
    'bfj': 'public class bfj {}',
    'bfz': 'public class bfz extends bfj { public boolean glide,crouch; public eei velocity=new eei(0,0,0); public boolean fr(){return glide;} public boolean bU(){return crouch;} public eei dl(){return velocity;} }',
    'fiv': 'public class fiv extends bfz {public float c,d,e;}',
    'fad': 'public class fad<T extends bfz> {public fad(){}}',
    'fee': 'public class fee {public float c,e,f,g; public fee b(String name){return new fee();}}',
    'fek': 'public class fek {}',
    'eei': 'public class eei {public final double c,d,e;public eei(double x,double y,double z){c=x;d=y;e=z;}public eei d(){double n=Math.sqrt(c*c+d*d+e*e);return n<1.0E-4?new eei(0,0,0):new eei(c/n,d/n,e/n);}}',
}
frames = []
for equipped, gliding, crouching, velocity in [
    (False, False, False, [0, 0, 0]),
    (True, False, False, [0, 0, 0]),
    (True, False, True, [0, 0, 0]),
    (True, True, False, [1, 0, 0]),
    (True, True, False, [0, -1, 0]),
    (True, True, False, [1, -1, 0]),
    (True, True, False, [0, -0.000001, 0]),
    (True, True, False, [0.2, 0.7, -0.8]),
    (False, True, False, [1, 0, 0]),
    (True, False, False, [0, 0, 0])]:
    for _ in range(8):
        frames.append({'emulate_elytra': True, 'elytra_equipped': equipped, 'gliding': gliding,
                       'crouching': crouching, 'velocity': velocity, 'render_frame': len(frames)})
rows = ',\n'.join('{%d,%d,%d,%s}' % (f['elytra_equipped'], f['gliding'], f['crouching'], ','.join(map(str, f['velocity']))) for f in frames)
sources['ElytraOracle'] = '''import java.lang.reflect.*;
public class ElytraOracle {
 public static void main(String[] args) throws Exception {
  Class<?> type=Class.forName("fbc");
  Object model=type.getConstructor(fee.class).newInstance(new fee());
  Method step=type.getMethod("a",bfz.class,float.class,float.class,float.class,float.class,float.class);
  fiv player=new fiv();
  double[][] rows={''' + rows + '''};
  for(double[] row:rows){
   float query=(float)Math.toDegrees(player.e);
   System.out.println(Float.floatToRawIntBits(query));
   player.glide=row[1]!=0;player.crouch=row[2]!=0;player.velocity=new eei(row[3],row[4],row[5]);
   if(row[0]!=0)step.invoke(model,player,0f,0f,0f,0f,0f);
  }
 }
}'''
for name, content in sources.items():
    (WORK / (name + '.java')).write_text(content, encoding='utf-8')
with zipfile.ZipFile(ROOT / 'vendor/minecraft-1.20.1/client.jar') as archive:
    vanilla = archive.read('fbc.class')
    (WORK / 'fbc.class').write_bytes(vanilla)
run = subprocess.run([toolchain['javac'], '-d', str(WORK), *map(str, sorted(WORK.glob('*.java')))], capture_output=True, text=True, timeout=20)
assert run.returncode == 0, run.stderr
run = subprocess.run([toolchain['java'], '-Xverify:all', '-cp', str(WORK), 'ElytraOracle'], capture_output=True, text=True, timeout=20)
assert run.returncode == 0, run.stderr
values = list(map(int, run.stdout.splitlines()))
assert len(values) == len(frames)
for frame, expected in zip(frames, values):
    frame['expected_f32_bits'] = expected & 0xffffffff
metadata = {'minecraft': '1.20.1', 'class': 'net.minecraft.client.model.ElytraModel',
            'official_class_sha256': hashlib.sha256(vanilla).hexdigest(),
            'scope': 'Unmodified official wing setup; player, model-part and Vec3 state carriers are minimal local stubs.'}
(ROOT / 'tests/elytra_java_vectors.py').write_text('# Generated by tools/generate_java_input_vectors.py\nMETADATA = ' + repr(metadata) + '\nVECTORS = ' + repr(frames) + '\n', encoding='utf-8')
(WORK / 'result.json').write_text(json.dumps({'metadata': metadata, 'frames': frames}, indent=2), encoding='utf-8')
print(json.dumps(metadata), 'frames', len(frames))
