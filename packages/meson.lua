-- The project already uses the Python launcher for its checks. Reuse that
-- interpreter for this build tool instead of downloading a second runtime.
package("meson")
    set_kind("binary")
    set_homepage("https://mesonbuild.com/")
    set_description("Meson build tool using the existing Python interpreter")
    set_license("Apache-2.0")
    add_urls("https://files.pythonhosted.org/packages/source/m/meson/meson-$(version).tar.gz")
    add_versions("1.6.1", "1eca49eb6c26d58bbee67fd3337d8ef557c0804e30a6d16bfdf269db997464de")
    set_policy("package.precompiled", false)
    on_install("@windows", function (package)
        local python = os.iorunv("py", {"-3", "-c", "import sys; print(sys.executable)"}):trim()
        assert(os.isfile(python), "Python launcher did not return an interpreter")
        os.vrunv(python, {"-m", "pip", "install", "--target=" .. package:installdir(), "."})
        package:addenv("PYTHONPATH", package:installdir())
        package:addenv("PATH", "bin")
    end)
    on_test(function (package)
        os.vrun("meson --version")
    end)
package_end()
